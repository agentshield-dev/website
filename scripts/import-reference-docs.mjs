import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import matter from "gray-matter";

const manifestName = ".agentshield-docs.json";
const marker = "Generated by agentshield-docs";
const authoredGuides = new Set(["_index.md", "contract.md", "style-guide.md", "tutorial.md", "write-a-plugin.md"]);
const pluginTitles = { aws: "AWS", cilium: "Cilium", istio: "Istio", kubernetes: "Kubernetes", agentgateway: "agentgateway", falco: "Falco" };

function readManifest(directory, required = false) {
  const filename = resolve(directory, manifestName);
  if (!existsSync(filename) && !required) return [];
  const names = JSON.parse(readFileSync(filename, "utf8"));
  if (!Array.isArray(names) || new Set(names).size !== names.length) throw new Error(`Invalid manifest: ${filename}`);
  for (const name of names) {
    if (typeof name !== "string" || !name.endsWith(".md") || name.startsWith("/") || name.includes("\\") || name.startsWith("../") || posix.normalize(name) !== name) {
      throw new Error(`Invalid generated page path: ${name}`);
    }
  }
  return names;
}

function readPage(filename) {
  return existsSync(filename) ? readFileSync(filename, "utf8") : null;
}

export function importReferenceDocs({ sourceDirectory, contentDirectory, replaceAuthoredPlugins = false }) {
  const sections = {
    reference: resolve(contentDirectory, "reference"),
    plugins: resolve(contentDirectory, "plugins"),
  };
  const previous = Object.fromEntries(Object.entries(sections).map(([section, directory]) => [section, readManifest(directory)]));
  const names = readManifest(sourceDirectory, true).filter((name) => !/^go\/plugins-.+-api\.md$/.test(name));
  const routes = new Map();
  for (const name of names) {
    if (/^go\/plugins-[a-z0-9-]+\.md$/.test(name)) {
      const destination = name.slice("go/plugins-".length);
      if (authoredGuides.has(destination)) throw new Error(`Generated plugin conflicts with authored guide: ${destination}`);
      routes.set(`/docs/reference/${name.slice(0, -3)}/`, `/docs/plugins/${destination.slice(0, -3)}/`);
    }
  }
  const plan = [];
  const current = { reference: [], plugins: [] };
  for (const name of names) {
    const original = readFileSync(resolve(sourceDirectory, name), "utf8");
    if (!original.includes(marker)) throw new Error(`Not a generated page: ${name}`);
    const plugin = routes.has(`/docs/reference/${name.slice(0, -3)}/`);
    const section = plugin ? "plugins" : "reference";
    const destination = plugin ? name.slice("go/plugins-".length) : name;
    const filename = resolve(sections[section], destination);
    const existing = readPage(filename);
    if (existing && !existing.includes(marker) && !(plugin && replaceAuthoredPlugins)) {
      throw new Error(`Refusing to overwrite authored page: ${filename}`);
    }
    const parsed = matter(original);
    let content = parsed.content;
    if (name === "go/_index.md") {
      content = content.replace(/^- \[plugins\/[^\n]+\n?/gm, "").trimEnd();
      if (routes.size) content += "\n\n[Plugin package documentation](/docs/plugins/) lives in the plugins section.\n";
    }
    for (const [oldRoute, newRoute] of routes) content = content.replaceAll(oldRoute, newRoute);
    let data = parsed.data;
    if (plugin) {
      const metadata = existing ? matter(existing).data : {};
      const identifier = destination.slice(0, -3);
      const provider = identifier.split("-")[0];
      const title = `${pluginTitles[provider] || provider}${identifier.endsWith("-api") ? " API" : ""}`;
      data = {
        ...data,
        ...metadata,
        title: metadata.title || title,
        aliases: [...new Set([...(metadata.aliases || []), `/reference/go/${name.slice("go/".length, -3)}/`])],
      };
      content = content.replace(/^(#{2,6} [^\n]+?) \{#(hdr-[^}]+)\}$/gm, (match, heading, anchor) => `<span id="${anchor}"></span>\n\n${heading}`);
    }
    plan.push({ filename, content: matter.stringify(content, data) });
    current[section].push(destination);
  }
  const removals = [];
  for (const [section, directory] of Object.entries(sections)) {
    for (const name of previous[section]) {
      if (current[section].includes(name)) continue;
      const filename = resolve(directory, name);
      const existing = readPage(filename);
      if (!existing) continue;
      if (!existing.includes(marker)) throw new Error(`Refusing to remove authored page: ${filename}`);
      removals.push(filename);
    }
  }
  for (const page of plan) {
    mkdirSync(dirname(page.filename), { recursive: true });
    writeFileSync(page.filename, page.content);
  }
  for (const filename of removals) rmSync(filename);
  for (const [section, directory] of Object.entries(sections)) {
    mkdirSync(directory, { recursive: true });
    writeFileSync(resolve(directory, manifestName), `${JSON.stringify(current[section].sort(), null, 2)}\n`);
  }
  return { references: current.reference.length, plugins: current.plugins.length, removed: removals.length };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({
    options: {
      source: { type: "string" },
      content: { type: "string", default: "docs/content" },
      "replace-authored-plugins": { type: "boolean", default: false },
    },
  });
  if (!values.source) throw new Error("--source is required");
  const result = importReferenceDocs({ sourceDirectory: resolve(values.source), contentDirectory: resolve(values.content), replaceAuthoredPlugins: values["replace-authored-plugins"] });
  console.log(`Imported ${result.references} reference pages and ${result.plugins} plugin pages; removed ${result.removed} obsolete generated files.`);
}