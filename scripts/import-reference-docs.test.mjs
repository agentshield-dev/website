import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";
import { test } from "node:test";
import { importReferenceDocs } from "./import-reference-docs.mjs";

const generated = (title, body = "Reference.") => `---\ntitle: "${title}"\nweight: 80\n---\n<!-- Generated by agentshield-docs. Do not edit manually. -->\n\n${body}\n`;
function fixture(context) {
  const root = mkdtempSync(join(tmpdir(), "docs-routing-"));
  context.after(() => rmSync(root, { recursive: true, force: true }));
  const sourceDirectory = join(root, "source");
  const contentDirectory = join(root, "content");
  const write = (filename, content) => {
    mkdirSync(dirname(filename), { recursive: true });
    writeFileSync(filename, content);
  };
  const source = (pages) => {
    for (const [name, content] of Object.entries(pages)) write(join(sourceDirectory, name), content);
    write(join(sourceDirectory, ".agentshield-docs.json"), JSON.stringify(Object.keys(pages)));
  };
  const snapshot = () => Object.fromEntries(readdirSync(contentDirectory, { recursive: true, withFileTypes: true }).filter((entry) => entry.isFile()).map((entry) => {
    const filename = join(entry.parentPath, entry.name);
    return [relative(contentDirectory, filename), readFileSync(filename, "utf8")];
  }));
  return { sourceDirectory, contentDirectory, write, source, snapshot };
}

test("routes plugins, rewrites package links, preserves guides and metadata, and is repeatable", (context) => {
  const fixtureData = fixture(context);
  const { sourceDirectory, contentDirectory, write, source, snapshot } = fixtureData;
  source({
    "go/_index.md": generated("Packages", "- [pkg/api](/docs/reference/go/pkg-api/)\n- [plugins/aws](/docs/reference/go/plugins-aws/)"),
    "go/pkg-api.md": generated("pkg/api", "See [AWS](/docs/reference/go/plugins-aws/)."),
    "go/plugins-aws.md": generated("plugins/aws", "## Telemetry {#hdr-Telemetry}\n\nProvider notes."),
    "go/plugins-cilium-api.md": generated("plugins/cilium/api"),
  });
  const authored = "---\ntitle: AWS\nweight: 6\n---\nHandwritten provider.\n";
  write(join(contentDirectory, "plugins/aws.md"), authored);
  write(join(contentDirectory, "plugins/tutorial.md"), "Authored tutorial.");
  write(join(contentDirectory, "plugins/write-a-plugin.md"), "Authored guide.");
  write(join(contentDirectory, "plugins/falco.md"), "Authored unmatched provider.");
  assert.throws(() => importReferenceDocs({ sourceDirectory, contentDirectory }), /Refusing to overwrite authored/);
  assert.equal(readFileSync(join(contentDirectory, "plugins/aws.md"), "utf8"), authored);
  importReferenceDocs({ sourceDirectory, contentDirectory, replaceAuthoredPlugins: true });
  const first = snapshot();
  assert.match(first["plugins/aws.md"], /title: AWS/);
  assert.match(first["plugins/aws.md"], /weight: 6/);
  assert.match(first["plugins/aws.md"], /\/reference\/go\/plugins-aws\//);
  assert.match(first["plugins/aws.md"], /<span id="hdr-Telemetry"><\/span>\n\n## Telemetry/);
  assert.equal(first["plugins/cilium-api.md"], undefined);
  assert.match(first["reference/go/pkg-api.md"], /\[AWS\]\(\/docs\/plugins\/aws\/\)/);
  assert.doesNotMatch(first["reference/go/_index.md"], /\[plugins\/aws\]/);
  assert.equal(first["plugins/tutorial.md"], "Authored tutorial.");
  assert.equal(first["plugins/write-a-plugin.md"], "Authored guide.");
  assert.equal(first["plugins/falco.md"], "Authored unmatched provider.");
  importReferenceDocs({ sourceDirectory, contentDirectory });
  assert.deepEqual(snapshot(), first);
});

test("removes only obsolete generated files in either section", (context) => {
  const { sourceDirectory, contentDirectory, write, source } = fixture(context);
  source({ "go/pkg-api.md": generated("pkg/api"), "go/plugins-aws.md": generated("plugins/aws") });
  write(join(contentDirectory, "reference/go/plugins-aws.md"), generated("plugins/aws"));
  write(join(contentDirectory, "reference/.agentshield-docs.json"), '["go/plugins-aws.md"]');
  write(join(contentDirectory, "reference/manual.md"), "Authored reference.");
  const first = importReferenceDocs({ sourceDirectory, contentDirectory });
  assert.equal(first.removed, 1);
  source({ "go/pkg-api.md": generated("pkg/api") });
  assert.equal(importReferenceDocs({ sourceDirectory, contentDirectory }).removed, 1);
  assert.equal(readFileSync(join(contentDirectory, "reference/manual.md"), "utf8"), "Authored reference.");
});

test("excludes internal plugin API packages and removes their previously generated copies", (context) => {
  const { sourceDirectory, contentDirectory, write, source, snapshot } = fixture(context);
  const providers = ["cilium", "istio", "kubernetes"];
  const pages = {
    "go/_index.md": generated("Packages", providers.map((provider) => `- [plugins/${provider}/api](/docs/reference/go/plugins-${provider}-api/)`).join("\n")),
  };
  for (const provider of providers) {
    const name = `${provider}-api.md`;
    pages[`go/plugins-${name}`] = generated(`plugins/${provider}/api`);
    write(join(contentDirectory, "plugins", name), generated(`plugins/${provider}/api`));
    write(join(contentDirectory, "reference/go", `plugins-${name}`), generated(`plugins/${provider}/api`));
  }
  write(join(contentDirectory, "plugins/.agentshield-docs.json"), JSON.stringify(providers.map((provider) => `${provider}-api.md`)));
  write(join(contentDirectory, "reference/.agentshield-docs.json"), JSON.stringify(providers.map((provider) => `go/plugins-${provider}-api.md`)));
  source(pages);
  assert.deepEqual(importReferenceDocs({ sourceDirectory, contentDirectory }), { references: 1, plugins: 0, removed: 6 });
  const output = snapshot();
  assert(!Object.keys(output).some((name) => name.endsWith("-api.md")));
  assert.doesNotMatch(output["reference/go/_index.md"], /plugins-.*-api/);
  assert.deepEqual(JSON.parse(output["plugins/.agentshield-docs.json"]), []);
  assert.deepEqual(JSON.parse(output["reference/.agentshield-docs.json"]), ["go/_index.md"]);
});

test("rejects invalid manifests and generated names that would overwrite authoring guides", (context) => {
  const { sourceDirectory, contentDirectory, write, source } = fixture(context);
  source({ "go/plugins-tutorial.md": generated("plugins/tutorial") });
  assert.throws(() => importReferenceDocs({ sourceDirectory, contentDirectory, replaceAuthoredPlugins: true }), /conflicts with authored guide/);
  write(join(sourceDirectory, ".agentshield-docs.json"), '["../outside.md"]');
  assert.throws(() => importReferenceDocs({ sourceDirectory, contentDirectory }), /Invalid generated page path/);
});

test("refuses to remove an owned page that has become authored", (context) => {
  const { sourceDirectory, contentDirectory, write, source } = fixture(context);
  source({ "go/pkg-api.md": generated("pkg/api") });
  write(join(contentDirectory, "plugins/.agentshield-docs.json"), '["aws.md"]');
  write(join(contentDirectory, "plugins/aws.md"), "Now authored.");
  assert.throws(() => importReferenceDocs({ sourceDirectory, contentDirectory }), /Refusing to remove authored page/);
});